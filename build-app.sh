#!/bin/bash
# Build termgrid.app, a double-clickable launcher for terminalsetup.py on macOS.
#
# The app carries its own copies of terminalsetup.py and termgrid.toml, so run
# this again after changing either of them.  Its icon is drawn by make-icon.py.  ~/.config/termgrid/termgrid.toml,
# if it exists, still takes precedence over the bundled config.
#
# Usage: ./build-app.sh [DEST_DIR]            (default: next to this script)
#        PYTHON=/path/to/python3 ./build-app.sh
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
dest=${1:-$here}
app="$dest/termgrid.app"

# A Finder launch gets a bare PATH, so the app needs the full path of a Python
# that has PyObjC.  Default to whichever python3 runs the build.
python=${PYTHON:-$(command -v python3)}
if ! "$python" -c 'import tomllib, AppKit, ScriptingBridge' 2>/dev/null; then
    echo "build-app: $python is not Python 3.11+ with PyObjC; install it with" >&2
    echo "  $python -m pip install pyobjc-framework-Cocoa pyobjc-framework-ScriptingBridge" >&2
    echo "or set PYTHON to one that has it" >&2
    exit 1
fi
quoted_python=${python//\\/\\\\}
quoted_python=${quoted_python//\"/\\\"}

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cat > "$work/termgrid.applescript" <<EOF
-- Tile the screens with Terminal windows as laid out in termgrid.toml.
-- Generated by build-app.sh; edit that instead.
set python to "$quoted_python"
set tool to POSIX path of (path to resource "terminalsetup.py")
try
	do shell script quoted form of python & " " & quoted form of tool
	tell application "Terminal" to activate
on error errorText
	display alert "termgrid failed" message errorText as critical
end try
EOF

osacompile -o "$work/termgrid.app" "$work/termgrid.applescript"
resources="$work/termgrid.app/Contents/Resources"
cp "$here/terminalsetup.py" "$here/termgrid.toml" "$resources/"
"$python" "$here/make-icon.py" "$resources/applet.icns"
plist="$work/termgrid.app/Contents/Info.plist"
plutil -replace CFBundleIdentifier -string local.termgrid "$plist"
plutil -replace NSAppleEventsUsageDescription -string "termgrid opens and arranges Terminal windows." "$plist"
# The script-app icon in Assets.car would win over applet.icns.
rm -f "$resources/Assets.car"
plutil -remove CFBundleIconName "$plist" 2>/dev/null || true
# Adding files invalidated the signature osacompile made.
codesign --force --sign - "$work/termgrid.app" 2>/dev/null

# Swap the new app in only once it is complete, so a failed build keeps the old one.
mkdir -p "$dest"
rm -rf "$app"
mv "$work/termgrid.app" "$app"
# Tell Finder and the Dock to pick up the new icon instead of a cached one.
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$app"
touch "$app"
echo "built $app (Python: $python)"
